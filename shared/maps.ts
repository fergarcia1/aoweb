type WorldGridCell = (typeof WORLD_MAP_GRID_CELLS)[number];

const WORLD_GRID_BY_COORD = new Map<string, WorldGridCell>();
const WORLD_GRID_BY_MAP_ID = new Map<string, WorldGridCell[]>();

for (const cell of WORLD_MAP_GRID_CELLS) {
  WORLD_GRID_BY_COORD.set(`${cell.gridX},${cell.gridY}`, cell);
  const entries = WORLD_GRID_BY_MAP_ID.get(cell.mapId);
  if (entries) {
    entries.push(cell);
  } else {
    WORLD_GRID_BY_MAP_ID.set(cell.mapId, [cell]);
  }
}

const EDGE_DELTAS: Record<MapEdge, { dx: number; dy: number; opposite: MapEdge }> = {
  up: { dx: 0, dy: -1, opposite: "down" },
  down: { dx: 0, dy: 1, opposite: "up" },
  left: { dx: -1, dy: 0, opposite: "right" },
  right: { dx: 1, dy: 0, opposite: "left" },
};

const MAP_EDGES: MapEdge[] = ["up", "down", "left", "right"];

/** Vecinos en la grilla mundial: N/S/E/O + NE/NW/SE/SW. */
const WORLD_GRID_NEIGHBOR_DELTAS = [
  { dx: 0, dy: -1 },
  { dx: 0, dy: 1 },
  { dx: -1, dy: 0 },
  { dx: 1, dy: 0 },
  { dx: 1, dy: -1 },
  { dx: -1, dy: -1 },
  { dx: 1, dy: 1 },
  { dx: -1, dy: 1 },
] as const;

function collectWorldGridAdjacentMapIds(mapId: string): string[] {
  const cells = WORLD_GRID_BY_MAP_ID.get(mapId);
  if (!cells?.length) {
    return [];
  }

  const neighbors = new Set<string>();
  for (const cell of cells) {
    for (const delta of WORLD_GRID_NEIGHBOR_DELTAS) {
      const neighbor = WORLD_GRID_BY_COORD.get(
        `${cell.gridX + delta.dx},${cell.gridY + delta.dy}`
      );
      if (neighbor && neighbor.mapId !== mapId) {
        neighbors.add(neighbor.mapId);
      }
    }
  }

  return [...neighbors];
}

/** Mapas vecinos para precarga: portales, bordes explícitos y grilla (8 direcciones). */
export function getAdjacentMapIds(mapId: string): string[] {
  const map = getMap(mapId);
  const adjacent = new Set<string>();

  for (const transition of map.transitions) {
    if (transition.toMapId !== mapId) {
      adjacent.add(transition.toMapId);
    }
  }

  for (const edge of MAP_EDGES) {
    const edgeTransition = map.edgeTransitions?.[edge];
    if (edgeTransition?.toMapId && edgeTransition.toMapId !== mapId) {
      adjacent.add(edgeTransition.toMapId);
    }
  }

  for (const gridNeighbor of collectWorldGridAdjacentMapIds(mapId)) {
    adjacent.add(gridNeighbor);
  }

  return [...adjacent];
}

/** Mapa actual + adyacentes para precarga acotada al entrar o cambiar de zona. */
export function getScopedPreloadMapIds(mapId: string): string[] {
  const ids = new Set<string>([mapId]);
  for (const adjacentId of getAdjacentMapIds(mapId)) {
    ids.add(adjacentId);
  }
  return [...ids];
}

function getWorldGridEdgeTransition(mapId: string, edge: MapEdge): EdgeTransition | undefined {
  const cells = WORLD_GRID_BY_MAP_ID.get(mapId);
  if (!cells) {
    return undefined;
  }
  const delta = EDGE_DELTAS[edge];
  for (const cell of cells) {
    const neighbor = WORLD_GRID_BY_COORD.get(`${cell.gridX + delta.dx},${cell.gridY + delta.dy}`);
    if (neighbor) {
      return { toMapId: neighbor.mapId, facing: delta.opposite };
    }
  }
  return undefined;
}

export function findTransition(
  mapId: string,
  tileX: number,
  tileY: number,
  facing?: "up" | "down" | "left" | "right",
  isBlocked: boolean = false,
  ignoreBlockedCheck: boolean = false
): MapTransition | undefined {
  const map = getMap(mapId);
  const directTransition = map.transitions.find((t) => t.tileX === tileX && t.tileY === tileY);
  if (directTransition) {
    return directTransition;
  }

  const margin = 10;
  const directionalEdge =
    facing === "up" && tileY <= margin
      ? "up"
      : facing === "down" && tileY >= map.height - 1 - margin
      ? "down"
      : facing === "left" && tileX <= margin
      ? "left"
      : facing === "right" && tileX >= map.width - 1 - margin
      ? "right"
      : undefined;

  const isOutOfBounds = tileX < 0 || tileX >= map.width || tileY < 0 || tileY >= map.height;
  if (!ignoreBlockedCheck && !isBlocked && !isOutOfBounds) {
    return undefined;
  }

  if (directionalEdge) {
    const edgeTransition =
      map.edgeTransitions?.[directionalEdge] ??
      getWorldGridEdgeTransition(mapId, directionalEdge);
    if (!edgeTransition) {
      return undefined;
    }

    const targetMap = getMap(edgeTransition.toMapId);
    const insetX = Math.min(
      EDGE_TRANSITION_TARGET_INSET,
      Math.max(1, Math.floor((targetMap.width - 1) / 2))
    );
    const insetY = Math.min(
      EDGE_TRANSITION_TARGET_INSET,
      Math.max(1, Math.floor((targetMap.height - 1) / 2))
    );

    if (directionalEdge === "up" || directionalEdge === "down") {
      const toTileX = Math.max(insetX, Math.min(targetMap.width - 1 - insetX, tileX));
      const toTileY = directionalEdge === "up" ? targetMap.height - 1 - insetY : insetY;
      return {
        tileX,
        tileY,
        toMapId: edgeTransition.toMapId,
        toTileX,
        toTileY,
        facing: edgeTransition.facing ?? directionalEdge,
      };
    }

    const toTileY = Math.max(insetY, Math.min(targetMap.height - 1 - insetY, tileY));
    const toTileX = directionalEdge === "left" ? targetMap.width - 1 - insetX : insetX;
    return {
      tileX,
      tileY,
      toMapId: edgeTransition.toMapId,
      toTileX,
      toTileY,
      facing: edgeTransition.facing ?? directionalEdge,
    };
  }

  const candidateEdges: ("up" | "down" | "left" | "right")[] = [];
  if (tileY === 0) candidateEdges.push("up");
  if (tileY === map.height - 1) candidateEdges.push("down");
  if (tileX === 0) candidateEdges.push("left");
  if (tileX === map.width - 1) candidateEdges.push("right");

  if (candidateEdges.length === 0) {
    return undefined;
  }

  const edge = facing && candidateEdges.includes(facing) ? facing : candidateEdges[0];
  const edgeTransition = map.edgeTransitions?.[edge] ?? getWorldGridEdgeTransition(mapId, edge);
  if (!edgeTransition) {
    return undefined;
  }

  const targetMap = getMap(edgeTransition.toMapId);
  const insetX = Math.min(
    EDGE_TRANSITION_TARGET_INSET,
    Math.max(1, Math.floor((targetMap.width - 1) / 2))
  );
  const insetY = Math.min(
    EDGE_TRANSITION_TARGET_INSET,
    Math.max(1, Math.floor((targetMap.height - 1) / 2))
  );
  if (edge === "up" || edge === "down") {
    const toTileX = Math.max(insetX, Math.min(targetMap.width - 1 - insetX, tileX));
    const toTileY = edge === "up" ? targetMap.height - 1 - insetY : insetY;
    return {
      tileX,
      tileY,
      toMapId: edgeTransition.toMapId,
      toTileX,
      toTileY,
      facing: edgeTransition.facing ?? edge,
    };
  }

  const toTileY = Math.max(insetY, Math.min(targetMap.height - 1 - insetY, tileY));
  const toTileX = edge === "left" ? targetMap.width - 1 - insetX : insetX;
  return {
    tileX,
    tileY,
    toMapId: edgeTransition.toMapId,
    toTileX,
    toTileY,
    facing: edgeTransition.facing ?? edge,
  };
}
